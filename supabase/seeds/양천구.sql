  SELECT id,
    CASE (row_number() OVER (ORDER BY id)) % 8
      WHEN 0 THEN ARRAY['에스프레소', '아메리카노', '카페라떼']
      WHEN 1 THEN ARRAY['아메리카노', '카푸치노', '핸드드립']
      WHEN 2 THEN ARRAY['카페라떼', '플랫화이트', '콜드브루']
      WHEN 3 THEN ARRAY['에스프레소', '핸드드립', '시그니처 라떼']
      WHEN 4 THEN ARRAY['아메리카노', '카페라떼', '싱글오리진']
      WHEN 5 THEN ARRAY['카푸치노', '콜드브루', '나이트로 콜드브루']
      WHEN 6 THEN ARRAY['플랫화이트', '에스프레소', '카페라떼']
      WHEN 7 THEN ARRAY['핸드드립', '아메리카노', '시그니처 블렌드']
    END AS menus
  FROM inserted
) t;
